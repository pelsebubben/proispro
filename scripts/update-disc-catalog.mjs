import assert from 'node:assert/strict'
import { writeFile } from 'node:fs/promises'

const response = await fetch('https://discit-api.fly.dev/disc', { signal: AbortSignal.timeout(20_000) })
assert.ok(response.ok, `Catalogue request failed: ${response.status}`)
const rows = await response.json()
assert.ok(Array.isArray(rows) && rows.length > 500, 'Unexpected catalogue response; snapshot was not changed')
const discs = new Map()
for (const row of rows) {
  assert.ok(typeof row.name === 'string' && row.name.trim() && typeof row.brand === 'string' && row.brand.trim())
  const category = String(row.category).toLowerCase()
  if (category === 'disc golf sets') continue
  const type = /putt|approach/.test(category) ? 'putter' : category.includes('mid') ? 'midrange'
    : /control|hybrid|fairway/.test(category) ? 'fairway' : category.includes('distance') ? 'distance'
      : category.includes('utility') ? 'utility' : null
  assert.ok(type, `Unknown category: ${row.category}`)
  const flight = Object.fromEntries(['speed', 'glide', 'turn', 'fade'].map(key => {
    assert.ok(row[key] !== null && row[key] !== '' && Number.isFinite(Number(row[key])), `Invalid ${key}: ${row.name}`)
    return [key, Number(row[key])]
  }))
  const key = `${row.brand.trim()}:${row.name.trim()}`.toLowerCase()
  discs.set(key, { id: key, name: row.name.trim(), brand: row.brand.trim(), type, ...flight })
}
const data = [...discs.values()].sort((a, b) => a.name.localeCompare(b.name, 'en') || a.brand.localeCompare(b.brand, 'en'))
await writeFile(new URL('../src/data/disc-catalog.ts', import.meta.url),
  '// Generated by scripts/update-disc-catalog.mjs. Sources and license: docs/disc-catalog.md.\n' +
  'export default ' + JSON.stringify(data, null, 0) + '\n')
console.log(`Updated ${data.length} unique disc molds; no images or product descriptions included.`)
